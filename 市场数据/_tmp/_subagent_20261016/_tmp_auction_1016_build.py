def clean(o):
    """%d格式化后遗留的多余转义（纯拼接字符串里的 %% ）统一还原为单个 %。"""
    if isinstance(o, str):
        return o.replace('%%', '%')
    if isinstance(o, list):
        return [clean(x) for x in o]
    if isinstance(o, dict):
        return {k: clean(v) for k, v in o.items()}
    return o

