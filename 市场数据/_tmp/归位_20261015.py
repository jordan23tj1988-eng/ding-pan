mp, miss, A, B, C = {}, [], [], [], []
for r in rd:
    code = str(r["代码"]).strip().zfill(6)
    name = r["名称"].strip()
    rs = reason.get(code)
    if code in MAP:
        big, seg = MAP[code]
        tier = "B"
        note = "B档：依据%s当日同花顺涨停原因原文作题材归类；未发现公告级证据，不标A档。" % D
