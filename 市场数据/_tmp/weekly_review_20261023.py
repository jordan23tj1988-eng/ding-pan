    x = json.load(open(os.path.join(L, '质量荐票结算_%s.json' % d), encoding='utf-8'))
    for t in (x.get('Top5') or []):
        r = t.get('执行收益')
        if r is None:
            continue
        row = (t.get('代码'), t.get('名称'), t.get('命中数'), r)
        (hit if int(t.get('命中数') or 0) > 0 else nohit).append(row)
