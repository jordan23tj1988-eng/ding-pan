out = {"日期": "20260821", "来源": "B档行业兜底(THS原因池停更,全池按申万行业归位)", "映射": {}}
with open(zt, encoding="utf-8-sig") as f:
    import csv
    for r in csv.DictReader(f):
        code = r["代码"].strip().zfill(6)
        name = r["名称"].strip()
        ind = (r.get("所属行业") or "").strip()
        lb = int(float(r.get("连板数", 1) or 1))
        if ind in IND:
            big, seg = IND[ind]
        else:
            big, seg = "其他/" + (ind or "未分类"), ind or "未分类"
        seg_txt = seg + (f"({lb}连板)" if lb >= 2 else "")
        out["映射"][code] = {
            "大方向": big, "环节": seg_txt,
            "催化": f"{ind}行业兜底" if ind else "行业缺失",
            "来源档": "B",
        }

p = os.path.join(BASE, "_学习", "题材归位_20260821.json")
json.dump(out, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print(f"归位 {len(out['映射'])} 只 -> {p}")
