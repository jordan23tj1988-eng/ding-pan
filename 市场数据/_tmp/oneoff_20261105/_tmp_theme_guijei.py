def is_junk(n):
    n = str(n)
    return ("ST" in n) or ("退" in n) or n.startswith("N") or n.startswith("C")


def classify(reason, ind):
    txt = str(reason or "")
    for big, kws in RULES:
        for kw in kws:
            if kw in txt:
                return big, kw
    # 行业兜底
    for k, v in IND_MAP.items():
        if k in str(ind or ""):
            return v, None
    return "其他/未归类", None


def main(d):
    zt = list(csv.DictReader(open(os.path.join(BASE, d, "zt_pool.csv"), encoding="utf-8-sig")))
    zt = [r for r in zt if not is_junk(r["名称"])]
    reasons = json.load(open(os.path.join(L, "涨停原因_%s.json" % d), encoding="utf-8")).get("映射") or {}
    mp = {}
    src = collections.Counter()
    for r in zt:
        code = r["代码"]; nm = r["名称"]
        rs = reasons.get(code) or {}
        reason = rs.get("原因") or ""
        ind = r.get("所属行业") or ""
        big, kw = classify(reason, ind)
        if reason:
            stage = "THS涨停原因原文（同花顺涨停池）"
            grade = "B"
            basis = "THS原因关键词:%s" % kw if kw else "THS原因原文"
            src["THS涨停原因"] += 1
        else:
            stage = "行业兜底（THS涨停池所属行业）"
            grade = "C"
            basis = "行业兜底:%s" % ind
            src["行业兜底"] += 1
        env = reason.split("+")[0].strip() if reason else (ind or "")
        nb = r.get("涨停统计") or ""
        lb = r.get("连板数") or "1"
        try:
            lbn = int(float(lb))
        except Exception:
            lbn = 1
        mp[code] = {
            "代码": code, "名称": nm, "大方向": big, "环节": env or ind,
            "催化": reason or (ind + "(行业兜底, 无THS原因)"),
            "催化状态": stage, "来源档": grade,
            "来源说明": ("%s档：依据%s当日同花顺涨停原因原文（_学习/涨停原因_%s.json，渠道=同花顺涨停池，证据级别=THS编辑聚合）"
                     "归纳大方向/环节；当日无公告级催化文件，不标A档；不继承上一交易日题材内容。" % (grade, d, d))
            if grade == "B" else
            ("C档：当日无THS涨停原因，仅按%s涨停池所属行业『%s』兜底归类，仅作宽度参考，不可当题材实锤。" % (d, ind)),
            "所属行业": ind, "连板口径": "%d天%d板" % (lbn, lbn), "首封": r.get("首次封板时间") or "",
            "开板次数": r.get("炸板次数") or "0", "玄学标签": None, "归类依据": basis,
        }
    agg = collections.Counter(v["大方向"] for v in mp.values())
    obj = {
        "日期": d, "as_of": d,
        "来源": "%s/zt_pool.csv（%d只，剔ST）；_学习/涨停原因_%s.json（同花顺涨停原因%d条，主源）"
                % (d, len(zt), d, len(reasons)),
        "口径": "逐只覆盖%s/zt_pool.csv全量%d只涨停股（剔ST）；以当日THS涨停原因原文归类题材（大方向/环节为对该原文的归纳）；无公告级证据不标A；不继承上一交易日题材内容。" % (d, len(zt)),
        "source_status": "pass" if len(mp) == len(zt) else "partial",
        "missing_fields": ["涨停原因"] if len(reasons) < len(zt) else [],
        "missing_detail": ([{"代码": r["代码"], "名称": r["名称"], "缺": "THS涨停原因", "处置": "行业兜底C档"} for r in zt if r["代码"] not in reasons] if len(reasons) < len(zt) else []),
        "counts": {"total": len(zt), "mapped": len(mp)},
        "A": sum(1 for v in mp.values() if v["来源档"] == "A"),
        "B": sum(1 for v in mp.values() if v["来源档"] == "B"),
        "C": sum(1 for v in mp.values() if v["来源档"] == "C"),
        "档计数": {"A": sum(1 for v in mp.values() if v["来源档"] == "A"),
                 "B": sum(1 for v in mp.values() if v["来源档"] == "B"),
                 "C": sum(1 for v in mp.values() if v["来源档"] == "C")},
        "来源明细": dict(src),
        "方向聚合": dict(agg.most_common()),
        "映射": mp,
    }
    p = os.path.join(L, "题材归位_%s.json" % d)
    json.dump(obj, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("written", p, os.path.getsize(p))
    print("counts", obj["counts"], "档", obj["档计数"], "来源", dict(src))
    print("方向聚合", json.dumps(obj["方向聚合"], ensure_ascii=False))
    unmapped = [v["名称"] for v in mp.values() if v["大方向"] == "其他/未归类"]
    print("未归类", unmapped)


