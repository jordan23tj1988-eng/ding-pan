for bk, cfg in tpl.items():
    if bk == "说明":
        continue
    for seg, ss in cfg.get("环节", {}).items():
        for pair in ss:
            if len(pair) >= 2:
                code2seg[str(pair[0]).zfill(6)] = (bk, seg)

