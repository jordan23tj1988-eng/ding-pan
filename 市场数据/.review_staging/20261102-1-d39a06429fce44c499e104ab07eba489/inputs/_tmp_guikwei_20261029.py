mapping, dir_agg, src_stat = {}, {}, {"THS涨停原因": 0, "行业兜底": 0, "公告催化": 0}
A, B, C = [], [], []
for r in zt:
    c = r["代码"]
    t = ths.get(c)
    has_ths = bool(t) and bool(t.get("limit_up_reason"))
    big, seg = M.get(c, (r.get("所属行业", "未归位"), "待补充（无THS原因·行业原文）"))
    reason = (t or {}).get("limit_up_reason") or (r.get("所属行业", "") + "（行业兜底）")
    tier = "B"
    src_stat["THS涨停原因" if has_ths else "行业兜底"] += 1
    if has_ths:
        src_desc = ("B档：依据20261029当日同花顺涨停原因原文（_学习/THS涨停池_20261029.json，"
                    "渠道=同花顺涨停池，证据级别=THS编辑聚合）作题材归类；当日无公告级催化补充文件，"
                    "不标A档；不继承上一交易日题材内容。")
    else:
        src_desc = ("B档：THS涨停原因缺失，按 zt_pool.csv 所属行业「%s」兜底归类；"
                    "证据级别=行业标签，未升级A档，如实标注缺口。" % r.get("所属行业", ""))
    bd = str(r.get("连板数") or "1")
    mapping[c] = {
        "代码": c, "名称": r["名称"], "大方向": big, "环节": seg,
        "催化": reason, "催化状态": "THS涨停原因原文（同花顺涨停池）" if has_ths else "行业兜底（THS原因缺失）",
        "来源档": tier, "来源说明": src_desc,
        "所属行业": r.get("所属行业", ""),
        "连板口径": ("首板" if bd == "1" else "%s天%s板" % (bd, bd)),
        "首封": (r.get("首次封板时间") or "")[:2] + ":" + (r.get("首次封板时间") or "")[2:4] if r.get("首次封板时间") else "",
    }
    (A if tier == "A" else B if tier == "B" else C).append(c)
    dir_agg[big] = dir_agg.get(big, 0) + 1

