def limit_px(code, pre):
    r = 0.20 if code[:2] in ("68", "30") else 0.10
    return round(pre * (1 + r), 2), r

def stat(f):
    rows = f["rows"]
    seal, zb = [], []
    for r in rows:
        L, rr = limit_px(r["code"], r["preClose"])
        if r["latest"] >= L - 0.005:
            seal.append(r)
        elif r["high"] >= L - 0.005:
            zb.append(r)
    return dict(
        ts=f["ts"], n=len(rows), seal=len(seal), zb=len(zb),
        up=sum(1 for r in rows if r["pct"] > 0),
        dn=sum(1 for r in rows if r["pct"] < 0),
        median=round(statistics.median([r["pct"] for r in rows]), 2),
        seal_list=[[r["code"], r["name"], r["pct"]] for r in seal],
        zb_list=[[r["code"], r["name"], r["high"], r["latest"], r["pct"]] for r in zb],
    )

